import logging
import os
from fastapi import FastAPI
from fastapi.responses import HTMLResponse
from fastapi.staticfiles import StaticFiles
from jinja2 import Environment, FileSystemLoader
from datetime import datetime

import yaml

from app.slurm_info import get_slurm_summary

# Configure a minimal, structured logger.  The app is unauthenticated and
# relies on the reverse proxy for access control, so we keep logging lean but
# useful for operations (uvicorn already logs each request line).
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(name)s %(message)s",
)
logger = logging.getLogger("pulsar.resenv")

# Resolve paths relative to the repository root so the app behaves the same
# regardless of the current working directory (e.g. when run behind a
# reverse proxy such as OpenResty).
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Setup Jinja2 for templating
env = Environment(loader=FileSystemLoader(os.path.join(BASE_DIR, "templates")))

app = FastAPI(title="PULSAR BYOC Information Service")

# Serve static assets (CSS/JS) from /static/...
app.mount(
    "/static",
    StaticFiles(directory=os.path.join(BASE_DIR, "static")),
    name="static",
)

# The Pulsar BYOC play writes two files onto the cluster master:
#   * byoc-connection.yml - the Galaxy BYOC summary (no secrets)
#   * byoc-secrets.yml    - the autogenerated RabbitMQ username + password
# Both live under pulsar_server_dir (/opt/pulsar by default). The app is
# stateless: it parses these files at request time instead of reading a
# prebuilt state.json.
PULSAR_SERVER_DIR = os.environ.get("PULSAR_SERVER_DIR", "/opt/pulsar")
CONNECTION_FILE = os.path.join(PULSAR_SERVER_DIR, "byoc-connection.yml")
SECRETS_FILE = os.path.join(PULSAR_SERVER_DIR, "byoc-secrets.yml")

# Service states.  UNAVAILABLE is reported when the connection summary has not
# been provisioned yet (byoc-connection.yml missing/unreadable).
STATE_UNAVAILABLE = "UNAVAILABLE"

# Bind address / port.  The app performs no authentication of its own; access
# control is provided by the FORC/OpenResty reverse proxy, which proxies the
# backend to this host:port.  The defaults match a local/standalone setup and
# are normally overridden per environment (e.g. by the systemd unit or the
# resenv image build):
#   PULSAR_RESENV_HOST - interface to bind (default 127.0.0.1)
#   PULSAR_RESENV_PORT - port to listen on (default 8080, matches the resenv)
BIND_HOST = os.environ.get("PULSAR_RESENV_HOST", "127.0.0.1")
BIND_PORT = int(os.environ.get("PULSAR_RESENV_PORT", "8080"))


def _read_yaml(path):
    """Read a YAML file, returning {} when missing or unreadable."""
    if not os.path.exists(path):
        logger.warning("file %s not found", path)
        return {}
    try:
        with open(path, "r") as f:
            data = yaml.safe_load(f)
        return data if isinstance(data, dict) else {}
    except (yaml.YAMLError, IOError) as exc:
        logger.warning("could not read %s: %s", path, exc)
        return {}


def load_config():
    """Build the dashboard configuration from the BYOC files.

    Returns a tuple of (pulsar_config, service_state).

    - When byoc-connection.yml is missing/unreadable, (None, "UNAVAILABLE") is
      returned so the template shows the "configuration not available yet"
      notice.
    - Otherwise a pulsar_config dict is built with the keys the template
      renders: username, password, max_cpus, max_ram_gib, max_gpus. The
      username comes from the connection summary, the password from the
      secrets file, and the max_* values from the summary's max_accepted_*
      (single-node maximum). Any max_* missing from the summary falls back to
      the live Slurm (sinfo) values.

    If no max_* values can be obtained at all (no summary and no Slurm), the
    config is considered incomplete and (None, "OPERATIONAL") is returned so
    the cards are not rendered.
    """
    connection = _read_yaml(CONNECTION_FILE)
    if not connection:
        logger.warning(
            "connection summary %s not found/empty; serving UNAVAILABLE view",
            CONNECTION_FILE,
        )
        return None, STATE_UNAVAILABLE

    secrets = _read_yaml(SECRETS_FILE)

    username = connection.get("username") or secrets.get("username")
    password = secrets.get("password")

    # The summary's max_accepted_* are the single-node maximums (the largest
    # worker), which is exactly what the Galaxy BYOC form wants. Fall back to
    # live Slurm (sinfo) for any value the summary does not carry.
    slurm = get_slurm_summary() or {}
    max_cpus = connection.get("max_accepted_cores") or slurm.get("max_cpus")
    max_ram_gib = connection.get("max_accepted_mem") or slurm.get("max_ram_gib")
    max_gpus = connection.get("max_accepted_gpus")
    if max_gpus in (None, ""):
        max_gpus = slurm.get("max_gpus", 0)

    if not all([username, password, max_cpus is not None,
                max_ram_gib is not None, max_gpus is not None]):
        logger.warning(
            "incomplete BYOC config (username=%s, password=%s, max_cpus=%s, "
            "max_ram=%s, max_gpus=%s); not rendering cards",
            bool(username), bool(password), max_cpus, max_ram_gib, max_gpus,
        )
        return None, "OPERATIONAL"

    return (
        {
            "username": username,
            "password": password,
            "max_cpus": max_cpus,
            "max_ram_gib": max_ram_gib,
            "max_gpus": max_gpus,
        },
        "OPERATIONAL",
    )


@app.get("/", response_class=HTMLResponse)
async def root():
    """Display the details needed to register the cluster with Galaxy (PULSAR)."""
    template = env.get_template("index.html")

    pulsar_config, service_state = load_config()
    slurm_summary = get_slurm_summary()
    current_year = datetime.now().year

    content = template.render(
        title="PULSAR BYOC - Connect your cluster to Galaxy",
        welcome_message="PULSAR BYOC",
        description="Information to register your Slurm cluster with Galaxy (bring your own compute)",
        current_year=current_year,
        pulsar_config=pulsar_config,
        service_state=service_state,
        slurm_summary=slurm_summary,
    )
    return HTMLResponse(content=content)


@app.get("/health")
async def health_check():
    """Health check endpoint for monitoring."""
    return {"status": "healthy", "service": "pulsar-BYOC-info"}


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(
        app,
        host=BIND_HOST,
        port=BIND_PORT,
        # reload=False is required in production; --reload spawns a watcher
        # process that is unsuitable for a supervised (systemd) service.
        reload=False,
    )
